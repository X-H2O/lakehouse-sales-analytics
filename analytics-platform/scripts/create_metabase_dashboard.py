DEFAULT_METABASE_URL = "http://localhost:3000"


@dataclass
class CardSpec:
    name: str
    query: str
    display: str
    row: int
    col: int
    size_x: int
    size_y: int
    visualization_settings: dict[str, Any]


class MetabaseClient:
    def __init__(self, base_url: str) -> None:
        self.base_url = base_url.rstrip("/")
        self.session_id: str | None = None

    def request(self, method: str, path: str, payload: dict[str, Any] | None = None) -> Any:
        headers = {"Content-Type": "application/json"}
        if self.session_id:
            headers["X-Metabase-Session"] = self.session_id

        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        request = Request(f"{self.base_url}{path}", data=data, headers=headers, method=method)
        try:
            with urlopen(request, timeout=60) as response:
                content = response.read().decode("utf-8")
                return json.loads(content) if content else None
        except HTTPError as exc:
            body = exc.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"{method} {path} failed: HTTP {exc.code}: {body}") from exc

    def login(self, email: str, password: str) -> None:
        result = self.request("POST", "/api/session", {"username": email, "password": password})
        self.session_id = result["id"]

    def list_databases(self) -> list[dict[str, Any]]:
        result = self.request("GET", "/api/database")
        if isinstance(result, dict) and "data" in result:
            return result["data"]
        if isinstance(result, list):
            return result
        return []

    def ensure_clickhouse_database(self) -> int:
        for database in self.list_databases():
            if database.get("name") == "Sales ADS ClickHouse":
                return int(database["id"])

        payload = {
            "name": "Sales ADS ClickHouse",
            "engine": "clickhouse",
            "details": {
                "host": "clickhouse",
                "port": 8123,
                "dbname": "sales_ads",
                "user": "sales_user",
                "password": "sales_password",
                "ssl": False,
            },
            "is_full_sync": True,
            "is_on_demand": False,
            "schedules": {},
        }
        database = self.request("POST", "/api/database", payload)
        database_id = int(database["id"])
        try:
            self.request("POST", f"/api/database/{database_id}/sync_schema")
        except RuntimeError as exc:
            print(f"Schema sync request skipped: {exc}")
        return database_id

    def find_collection_id(self, name: str) -> int | None:
        result = self.request("GET", "/api/collection")
        collections = result.get("data", result) if isinstance(result, dict) else result
        for collection in collections:
            if collection.get("name") == name:
                return int(collection["id"])
        return None

    def ensure_collection(self, name: str, description: str) -> int:
        collection_id = self.find_collection_id(name)
        if collection_id is not None:
            return collection_id
        collection = self.request("POST", "/api/collection", {"name": name, "description": description})
        return int(collection["id"])

    def create_card(self, database_id: int, collection_id: int, spec: CardSpec) -> int:
        payload = {
            "name": spec.name,
            "description": "Generated by scripts/create_metabase_dashboard.py",
            "display": spec.display,
            "dataset_query": {
                "database": database_id,
                "type": "native",
                "native": {"query": spec.query},
            },
            "visualization_settings": spec.visualization_settings,
            "collection_id": collection_id,
        }

        for card in self.list_cards():
            if card.get("name") == spec.name and card.get("collection_id") == collection_id:
                self.request("PUT", f"/api/card/{int(card['id'])}", payload)
                return int(card["id"])

        card = self.request("POST", "/api/card", payload)
        return int(card["id"])

    def list_cards(self) -> list[dict[str, Any]]:
        result = self.request("GET", "/api/card")
        if isinstance(result, dict):
            return result.get("data") or result.get("value") or []
        if isinstance(result, list):
            return result
        return []

    def list_dashboards(self) -> list[dict[str, Any]]:
        result = self.request("GET", "/api/dashboard")
        if isinstance(result, dict):
            return result.get("data") or result.get("value") or []
        if isinstance(result, list):
            return result
        return []

    def ensure_dashboard(self, collection_id: int) -> int:
        for dashboard in self.list_dashboards():
            if dashboard.get("name") == "Sales Analytics Dashboard" and dashboard.get("collection_id") == collection_id:
                return int(dashboard["id"])

        payload = {
            "name": "Sales Analytics Dashboard",
            "description": "Daily sales, conversion, LTV, contribution, and abnormal refund metrics.",
            "collection_id": collection_id,
        }
        dashboard = self.request("POST", "/api/dashboard", payload)
        return int(dashboard["id"])

    def update_dashboard_cards(self, dashboard_id: int, card_layouts: list[tuple[int, CardSpec]]) -> None:
        dashboard = self.request("GET", f"/api/dashboard/{dashboard_id}")
        existing_dashcards = dashboard.get("dashcards", [])
        dashcard_by_card_id = {}
        for dashcard in existing_dashcards:
            card = dashcard.get("card") or {}
            card_id = dashcard.get("card_id") or card.get("id")
            if card_id is not None:
                dashcard_by_card_id[int(card_id)] = dashcard

        cards = []
        next_temp_id = -1
        for card_id, spec in card_layouts:
            existing = dashcard_by_card_id.get(card_id)
            dashcard_id = int(existing["id"]) if existing else next_temp_id
            if not existing:
                next_temp_id -= 1
            cards.append(
                {
                    "id": dashcard_id,
                    "card_id": card_id,
                    "row": spec.row,
                    "col": spec.col,
                    "size_x": spec.size_x,
                    "size_y": spec.size_y,
                    "parameter_mappings": existing.get("parameter_mappings", []) if existing else [],
                    "series": existing.get("series", []) if existing else [],
                }
            )

        self.request("PUT", f"/api/dashboard/{dashboard_id}/cards", {"cards": cards, "tabs": []})


