def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create Metabase sales analytics dashboard.")
    parser.add_argument("--url", default=DEFAULT_METABASE_URL)
    parser.add_argument("--email", required=True, help="Metabase admin email.")
    parser.add_argument("--password", required=True, help="Metabase admin password.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    client = MetabaseClient(args.url)
    client.login(args.email, args.password)

    database_id = client.ensure_clickhouse_database()
    collection_id = client.ensure_collection(
        "Sales Analytics",
        "Generated dashboards and questions for the local sales analytics project.",
    )
    dashboard_id = client.ensure_dashboard(collection_id)

    card_layouts = []
    for spec in card_specs():
        card_id = client.create_card(database_id, collection_id, spec)
        card_layouts.append((card_id, spec))
        print(f"Created card {card_id}: {spec.name}")

    client.update_dashboard_cards(dashboard_id, card_layouts)
    print(f"Dashboard created: {args.url.rstrip('/')}/dashboard/{dashboard_id}")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(exc, file=sys.stderr)
        sys.exit(1)
